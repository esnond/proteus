#!/bin/sh
# seccomp whitelist generator: strace the real daemon through one
# session (init, scheduled burst, live listener, ipc) and write the
# compiled in whitelist. the trace target is the static binary, the
# same shape the enforcement test runs, otherwise loader syscalls leak
# in or drop out. run on the privileged bench, then:
# make clean && make SECCOMP=1 STATIC=1. the whitelist is never hand
# written.
set -e
cd "$(dirname "$0")/.."
OUT=src/seccomp_profile.h
TRACE=${TRACE:-$(mktemp)}
# trap kept off for generation diagnostics

make -s clean > /dev/null 2>&1
make -s STATIC=1 > /dev/null 2>&1
# trace inside a throwaway user+net namespace: --nft needs cap_net_admin
# and the host ruleset must never be touched. only the daemon runs under
# strace (the ip setup stays outside), so no iproute2 syscalls leak in
# the registrar runs beside the trace so getrandom and the token table
# enter the profile; without it the daemon dies under seccomp on the
# first registration instead of on the first boot
rm -f /tmp/seccomp_probe.sock
( sleep 1.8; ./proteusctl register --socket /tmp/seccomp_probe.sock \
    >/dev/null 2>&1 ) &
REG=$!
if unshare -Urn true 2>/dev/null; then
    unshare -Urn sh -c "ip link set lo up; strace -f -qq -o '$TRACE' \
        ./proteusd -s 2 -d 5 -r --listen --socket /tmp/seccomp_probe.sock \
        --nft --addr 127.0.0.1 -e tests/fixtures/burst.csv -o /dev/null" \
        2>/dev/null || true
else
    strace -f -qq -o "$TRACE" ./proteusd -s 2 -d 5 -r --listen \
        --socket /tmp/seccomp_probe.sock --nft \
        -e tests/fixtures/burst.csv -o /dev/null 2>/dev/null || true
fi
wait "$REG" 2>/dev/null || true

# strace line formats differ across versions and -f modes, the syscall
# name is always the word before the first opening paren; every name is
# checked against the kernel syscall table so that parser noise cannot
# smuggle an unknown define in
sed -E 's/^\[[^]]*\]//; s/^[0-9]+ +//' "$TRACE" \
    | grep -oE '[a-z0-9_]+\(' | tr -d '(' | sort -u > /tmp/seccomp_names.txt
: > /tmp/seccomp_allow.txt
UNISTD=$(ls /usr/include/x86_64-linux-gnu/asm/unistd_64.h \
           /usr/include/asm/unistd_64.h 2>/dev/null | head -1)
while read -r sc; do
    [ -n "$sc" ] || continue
    [ -n "$UNISTD" ] || break
    awk -v s="$sc" '$2 == "__NR_" s {found=1} END {exit !found}' \
        "$UNISTD" && echo "    __NR_$sc," >> /tmp/seccomp_allow.txt
done < /tmp/seccomp_names.txt
N=$(grep -c __NR_ /tmp/seccomp_allow.txt || true)
if [ "$N" -lt 5 ]; then
    echo "FATAL: parser produced $N syscalls, strace format mismatch" >&2
    rm -f /tmp/seccomp_names.txt /tmp/seccomp_allow.txt
    exit 1
fi

{
    echo "/* generated by tools/seccomp_gen.sh from a strace of the"
    echo "   real daemon, do not edit by hand. rebuild:"
    echo "   make clean && make SECCOMP=1 STATIC=1 */"
    echo "#include <stdint.h>"
    echo "#define SECCOMP_ALLOW_N $N"
    echo "static const uint32_t seccomp_allow[SECCOMP_ALLOW_N] = {"
    cat /tmp/seccomp_allow.txt
    echo "};"
} > "$OUT"
rm -f /tmp/seccomp_names.txt /tmp/seccomp_allow.txt
echo "wrote $OUT: $N syscalls"
